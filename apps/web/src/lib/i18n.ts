const dictionaries: Record<Locale, Dict> = { ru, en };

interface I18nState {
  locale: Locale;
  setLocale: (locale: Locale) => void;
}

export const useI18nStore = create<I18nState>((set) => ({
  locale: (localStorage.getItem('elian.locale') as Locale) || (navigator.language.startsWith('ru') ? 'ru' : 'en'),
  setLocale: (locale) => {
    localStorage.setItem('elian.locale', locale);
    document.documentElement.lang = locale;
    set({ locale });
  },
}));

export function useT(): (key: string, fallback?: string) => string {
  const locale = useI18nStore((state) => state.locale);
  return (key, fallback) => dictionaries[locale][key] ?? fallback ?? key;
}

export function tFor(locale: Locale, key: string): string {
  return dictionaries[locale][key] ?? key;
}
